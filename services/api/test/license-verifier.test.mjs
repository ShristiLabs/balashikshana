// B2B license verifier unit tests (issue #70): licensing-core semantics
// implemented in JS — canonical JSON, the pinned GOLDEN VECTOR (format
// compatibility with the Rust implementation via RFC 8032 determinism),
// the full failure taxonomy, serde-parity (extra fields ignored), and the
// key-resolution posture (dev fallback / env / fail-closed).

import { test, describe } from "vitest";
import assert from "node:assert/strict";
import * as ed from "@noble/ed25519";
import { sha512 } from "@noble/hashes/sha2.js";
import crypto from "node:crypto";
import {
  canonicalClaimsJson,
  extractClaims,
  createLicenseVerifier,
  resolveLicenseVerifier,
  EXPECTED_PRODUCT_ID,
  PUBLIC_KEY_ENV_VAR,
  DEV_LICENSE_KEY_SEED
} from "../license-verifier.mjs";

// Wire SHA-512 exactly like the module does (mobile verify.ts pattern).
{
  const merge = (msgs) => {
    const total = msgs.reduce((n, m) => n + m.length, 0);
    const out = new Uint8Array(total);
    let offset = 0;
    for (const m of msgs) {
      out.set(m, offset);
      offset += m.length;
    }
    return out;
  };
  ed.etc.sha512Sync = (...m) => sha512(merge(m));
}

const DEV_SEED = Buffer.from(DEV_LICENSE_KEY_SEED, "utf8");

function signLicense(claims, seed = DEV_SEED) {
  const canonical = canonicalClaimsJson(claims);
  const signature = Buffer.from(ed.sign(Buffer.from(canonical, "utf8"), seed)).toString("base64");
  return { ...claims, signature };
}

function baseClaims(overrides = {}) {
  return {
    license_id: "lic_test_001",
    product_id: EXPECTED_PRODUCT_ID,
    customer: "Test Elementary School",
    plan: "school",
    seats: 10,
    instance_id: "inst_test_001",
    issued_at: "2026-10-01T00:00:00Z",
    expires_at: "2099-01-01T00:00:00Z",
    features: ["roster-import"],
    ...overrides
  };
}

describe("canonicalClaimsJson (licensing-core canonical.rs parity)", () => {
  test("keys are sorted recursively, arrays keep order, output is compact", () => {
    const claims = baseClaims({ features: ["b", "a", "c"] });
    const canonical = canonicalClaimsJson(claims);
    const parsed = JSON.parse(canonical);
    assert.deepEqual(Object.keys(parsed), Object.keys(parsed).slice().sort((a, b) => (a < b ? -1 : a > b ? 1 : 0)));
    assert.deepEqual(parsed.features, ["b", "a", "c"]);
    // Compact = no INSIGNIFICANT whitespace (string values may contain
    // spaces): re-serializing the parsed value must reproduce the bytes.
    assert.equal(JSON.stringify(JSON.parse(canonical)), canonical);
    // Nested objects sort too.
    const nested = canonicalClaimsJson({ z: 1, a: { y: 2, b: 3 } });
    assert.equal(nested, '{"a":{"b":3,"y":2},"z":1}');
  });

  test("code-POINT ordering, not UTF-16 code-unit ordering (serde BTreeMap UTF-8 parity)", () => {
    // U+FF21 (fullwidth A, BMP) sorts BEFORE U+10000 (supplementary plane)
    // by code point; UTF-16 code-unit order would reverse them.
    const canonical = canonicalClaimsJson({ "\u{10000}": 1, "\uFF21": 2 });
    assert.deepEqual(Object.keys(JSON.parse(canonical)), ["\uFF21", "\u{10000}"]);
  });
});

describe("GOLDEN VECTOR (format compatibility with licensing-core)", () => {
  // Generated over the PUBLIC licensing-core dev seed (keys.rs DEV_KEY_SEED,
  // public by design). Ed25519 is deterministic per RFC 8032, so these are
  // the exact bytes ed25519-dalek (Rust, licensing-core) produces for the
  // same seed + canonical message — a signature generated by the real
  // licensing server over these claims verifies against them.
  const GOLDEN_CANONICAL =
    '{"customer":"Golden Elementary School District","expires_at":"2027-10-01T00:00:00Z","features":["roster-import","seat-validation"],"instance_id":"inst_golden_001","issued_at":"2026-10-01T00:00:00Z","license_id":"lic_golden_001","plan":"school","product_id":"balashikshana","seats":25}';
  const GOLDEN_SIGNATURE =
    "8UHa+x/zTao1//X6BpRUa50g6dcA50ypNvKbEZIcRusaQRUvFBb9s2tTD92aam+SU8Q0qXl7sciAtXI8YpViBw==";

  test("canonical form of the golden claims is byte-identical", () => {
    const claims = {
      license_id: "lic_golden_001",
      product_id: "balashikshana",
      customer: "Golden Elementary School District",
      plan: "school",
      seats: 25,
      instance_id: "inst_golden_001",
      issued_at: "2026-10-01T00:00:00Z",
      expires_at: "2027-10-01T00:00:00Z",
      features: ["roster-import", "seat-validation"]
    };
    assert.equal(canonicalClaimsJson(claims), GOLDEN_CANONICAL);
  });

  test("the golden signature verifies (dev key) and claims round-trip", () => {
    const verifier = createLicenseVerifier({ now: () => Date.parse("2026-10-26T00:00:00Z") });
    const file = {
      license_id: "lic_golden_001",
      product_id: "balashikshana",
      customer: "Golden Elementary School District",
      plan: "school",
      seats: 25,
      instance_id: "inst_golden_001",
      issued_at: "2026-10-01T00:00:00Z",
      expires_at: "2027-10-01T00:00:00Z",
      features: ["roster-import", "seat-validation"],
      signature: GOLDEN_SIGNATURE
    };
    const outcome = verifier.verifyLicenseFile(file);
    assert.ok(outcome.ok, `expected ok, got ${outcome.code}: ${outcome.message}`);
    assert.equal(outcome.claims.license_id, "lic_golden_001");
    assert.equal(outcome.claims.seats, 25);
    assert.equal(outcome.canonical, GOLDEN_CANONICAL);
  });
});

describe("verifyLicenseFile — failure taxonomy (licensing-core verifier.rs parity)", () => {
  const verifier = createLicenseVerifier({});

  test("valid license verifies", () => {
    const outcome = verifier.verifyLicenseFile(signLicense(baseClaims()));
    assert.ok(outcome.ok, outcome.code);
  });

  test("expired license -> expired (whole-claims, after signature)", () => {
    const file = signLicense(baseClaims({ expires_at: "2020-01-01T00:00:00Z" }));
    const outcome = verifier.verifyLicenseFile(file);
    assert.equal(outcome.code, "expired");
  });

  test("expiry boundary: now == expires_at is NOT expired (Rust: now > expires_at)", () => {
    const fixed = createLicenseVerifier({ now: () => Date.parse("2030-01-01T00:00:00Z") });
    const file = signLicense(baseClaims({ expires_at: "2030-01-01T00:00:00Z" }));
    assert.ok(fixed.verifyLicenseFile(file).ok);
  });

  test("tampered claims (seats raised) -> invalid-signature", () => {
    const file = signLicense(baseClaims({ seats: 10 }));
    file.seats = 999;
    assert.equal(verifier.verifyLicenseFile(file).code, "invalid-signature");
  });

  test("tampered signature byte -> invalid-signature", () => {
    const file = signLicense(baseClaims());
    const bytes = Buffer.from(file.signature, "base64");
    bytes[bytes.length - 1] ^= 0xff;
    file.signature = bytes.toString("base64");
    assert.equal(verifier.verifyLicenseFile(file).code, "invalid-signature");
  });

  test("wrong signing key -> invalid-signature", () => {
    const stranger = crypto.randomBytes(32);
    const file = signLicense(baseClaims(), stranger);
    assert.equal(verifier.verifyLicenseFile(file).code, "invalid-signature");
  });

  test("non-strict base64 / wrong length signature -> invalid-signature", () => {
    const file = signLicense(baseClaims());
    assert.equal(verifier.verifyLicenseFile({ ...file, signature: "not!base64!!" }).code, "invalid-signature");
    const short = Buffer.from(file.signature, "base64").subarray(0, 63).toString("base64");
    assert.equal(verifier.verifyLicenseFile({ ...file, signature: short }).code, "invalid-signature");
  });

  test("product pin: license for another product -> product-mismatch; unpinned verifier accepts", () => {
    const file = signLicense(baseClaims({ product_id: "madhyamas" }));
    assert.equal(verifier.verifyLicenseFile(file).code, "product-mismatch");
    const unpinned = createLicenseVerifier({ expectedProductId: null });
    assert.ok(unpinned.verifyLicenseFile(file).ok);
  });

  test("instance pin: mismatch -> instance-mismatch", () => {
    const pinned = createLicenseVerifier({ expectedInstanceId: "inst_mine" });
    const file = signLicense(baseClaims({ instance_id: "inst_other" }));
    assert.equal(pinned.verifyLicenseFile(file).code, "instance-mismatch");
  });

  test("parse errors: missing field, wrong types, non-canonical timestamps", () => {
    const file = signLicense(baseClaims());
    const { signature } = file;
    delete file.customer;
    assert.equal(verifier.verifyLicenseFile({ ...baseClaims(), signature, seats: "25" }).code, "parse-error");
    assert.equal(
      verifier.verifyLicenseFile({ ...baseClaims({ issued_at: "2026-10-01 00:00:00" }), signature }).code,
      "parse-error"
    );
    assert.equal(
      verifier.verifyLicenseFile({ ...baseClaims({ issued_at: "2026-10-01T00:00:00+00:00" }), signature }).code,
      "parse-error"
    );
    assert.equal(verifier.verifyLicenseFile({ ...baseClaims(), features: "roster-import", signature }).code, "parse-error");
    assert.equal(verifier.verifyLicenseFile(null).code, "parse-error");
    assert.equal(verifier.verifyLicenseFile([1, 2]).code, "parse-error");
    // Missing signature entirely.
    assert.equal(verifier.verifyLicenseFile(baseClaims()).code, "parse-error");
  });

  test("SERDE PARITY: unknown extra fields are ignored and the signature still verifies", () => {
    const file = signLicense(baseClaims());
    const withExtra = { ...file, future_field: "ignored", another: { nested: true } };
    // The signature covers ONLY the known claims re-serialized canonically,
    // exactly like Rust's serde(flatten) round-trip.
    assert.ok(verifier.verifyLicenseFile(withExtra).ok);
  });

  test("seat bounds: seats = 0 and u32 max parse; negative / fractional / overflow do not", () => {
    assert.ok(extractClaims({ ...baseClaims({ seats: 0 }), signature: "x".repeat(4) }).ok);
    assert.ok(extractClaims({ ...baseClaims({ seats: 4294967295 }), signature: "x".repeat(4) }).ok);
    assert.equal(extractClaims({ ...baseClaims({ seats: -1 }), signature: "x".repeat(4) }).code, "parse-error");
    assert.equal(extractClaims({ ...baseClaims({ seats: 1.5 }), signature: "x".repeat(4) }).code, "parse-error");
    assert.equal(extractClaims({ ...baseClaims({ seats: 4294967296 }), signature: "x".repeat(4) }).code, "parse-error");
  });
});

describe("key resolution posture", () => {
  test("absent env -> dev source; production reports the loud boot error", () => {
    const dev = resolveLicenseVerifier({}, { isProduction: false });
    assert.equal(dev.source, "dev");
    assert.equal(dev.bootError, null);
    const prod = resolveLicenseVerifier({}, { isProduction: true });
    assert.equal(prod.source, "dev");
    assert.ok(prod.bootError.includes(PUBLIC_KEY_ENV_VAR));
    // The dev fallback really is the licensing-core dev key: the golden
    // vector (signed by the dev seed) verifies against it.
    assert.ok(
      prod.verifier.verifyLicenseFile({
        license_id: "lic_golden_001",
        product_id: "balashikshana",
        customer: "Golden Elementary School District",
        plan: "school",
        seats: 25,
        instance_id: "inst_golden_001",
        issued_at: "2026-10-01T00:00:00Z",
        expires_at: "2027-10-01T00:00:00Z",
        features: ["roster-import", "seat-validation"],
        signature: "8UHa+x/zTao1//X6BpRUa50g6dcA50ypNvKbEZIcRusaQRUvFBb9s2tTD92aam+SU8Q0qXl7sciAtXI8YpViBw=="
      }).ok
    );
  });

  test("valid env key -> env source, verifies licenses signed by that key ONLY", () => {
    const seed = crypto.randomBytes(32);
    const publicKeyB64 = Buffer.from(ed.getPublicKey(seed)).toString("base64");
    const resolved = resolveLicenseVerifier({ [PUBLIC_KEY_ENV_VAR]: publicKeyB64 });
    assert.equal(resolved.source, "env");
    assert.equal(resolved.bootError, null);
    const good = resolved.verifier.verifyLicenseFile(signLicense(baseClaims(), seed));
    assert.ok(good.ok);
    // A dev-seed license must NOT verify against the stranger key.
    assert.equal(resolved.verifier.verifyLicenseFile(signLicense(baseClaims())).code, "invalid-signature");
  });

  test("INVALID env key -> fail CLOSED: verifier-unavailable on everything + boot error", () => {
    const resolved = resolveLicenseVerifier({ [PUBLIC_KEY_ENV_VAR]: "not-base64!!!" });
    assert.equal(resolved.source, "disabled");
    assert.ok(resolved.bootError.includes("fail closed"));
    const outcome = resolved.verifier.verifyLicenseFile(signLicense(baseClaims()));
    assert.equal(outcome.code, "verifier-unavailable");
  });
});
